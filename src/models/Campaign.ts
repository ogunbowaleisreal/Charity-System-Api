import { Schema, model } from "mongoose";

const campaignSchema = new Schema({
    name: {
        type: String,
        required: true,
    },
    description: {
        type: String,
        required: true,
    },
    startDate: {
        type: Date,
        required: true,
    },
    endDate: {
        type: Date,
        required: true,
    },
    status: {
        type: String,
        required: true,
    }

}, { timestamps: true });

export default model("Campaign", campaignSchema);